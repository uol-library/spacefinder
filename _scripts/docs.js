/**
 * Generates the API documentation in docs/api from the JSDoc comments in
 * the core modules (assets/js/modules), one page per module.
 *
 * Each page starts with the comment at the top of the module (if there is
 * one), followed by the documentation jsdoc-to-markdown generates for its
 * functions and classes. Pages for modules which no longer exist are removed.
 *
 * config.mjs is left out because it contains Liquid, which JSDoc can't parse.
 *
 * Run from the repository root:
 *   npm run docs
 */

'use strict';

const fs      = require('fs');
const path    = require('path');
const jsdoc2md = require('jsdoc-to-markdown');

const MODULES_DIR = path.resolve(__dirname, '../assets/js/modules');
const OUTPUT_DIR  = path.resolve(__dirname, '../docs/api');
const EXCLUDE     = ['config.mjs'];
const MARKER      = '<!-- generated by _scripts/docs.js - do not edit -->';

/* JSDoc only reads .js files by default */
const JSDOC_CONFIG = path.join(OUTPUT_DIR, '.jsdoc.json');

/**
 * Gets the comment at the very top of a file as markdown. Lines indented by
 * two or more spaces (e.g. aligned lists of routes) are kept as code blocks.
 */
function getFileComment(source) {
    let match = source.match(/^\s*\/\*\*([\s\S]*?)\*\//);
    if (!match) {
        return '';
    }
    let lines = match[1].split('\n')
        .map(line => line.replace(/^\s*\* ?/, '').replace(/\s+$/, ''))
        .filter(line => !/^@/.test(line));
    let out = [];
    let inCode = false;
    lines.forEach(line => {
        let code = /^ {2,}\S/.test(line);
        if (code !== inCode) {
            out.push('```');
            inCode = code;
        }
        out.push(code ? line.replace(/^ {2}/, '') : line);
    });
    if (inCode) {
        out.push('```');
    }
    return out.join('\n').trim();
}

/**
 * Gets the names a module exports, so pages can say which functions other
 * modules (and dataset modules) can import
 */
function getExports(source) {
    let names = [];
    let re = /^export\s+(?:async\s+)?(?:function\*?|const|let|class)\s+(\w+)/gm;
    let match;
    while ((match = re.exec(source)) !== null) {
        names.push('`' + match[1] + '`');
    }
    return names.length ? '**Exports:** ' + names.join(', ') : '**Exports:** nothing (this module sets up event listeners when it is imported)';
}

async function main() {
    fs.mkdirSync(OUTPUT_DIR, { recursive: true });
    fs.writeFileSync(JSDOC_CONFIG, JSON.stringify({ source: { includePattern: '.+\\.m?js$' } }));
    let modules = fs.readdirSync(MODULES_DIR).filter(f => f.endsWith('.mjs') && !EXCLUDE.includes(f)).sort();
    let written = [];
    try {
        for (let file of modules) {
            let source = fs.readFileSync(path.join(MODULES_DIR, file), 'utf8');
            /* JSDoc drops the documentation for exported classes, so remove export from them */
            let api = await jsdoc2md.render({ source: source.replace(/^export\s+class\s/gm, 'class '), configure: JSDOC_CONFIG, 'heading-depth': 2, 'global-index-format': 'grouped' });
            let name = path.basename(file, '.mjs');
            let page = [
                '---',
                'title: ' + file,
                'parent: API',
                'nav_order: ' + (written.length + 1),
                '---',
                MARKER,
                '{% raw %}',
                '# ' + file,
                '',
                '[Source](https://github.com/uol-library/spacefinder/blob/develop/assets/js/modules/' + file + ')',
                '',
                getFileComment(source),
                '',
                getExports(source),
                '',
                api.trim() || '_No documented functions._',
                '{% endraw %}',
                ''
            ].join('\n');
            fs.writeFileSync(path.join(OUTPUT_DIR, name + '.md'), page.replace(/\n{3,}/g, '\n\n'));
            written.push(name + '.md');
            console.log('Wrote docs/api/' + name + '.md');
        }
    } finally {
        fs.unlinkSync(JSDOC_CONFIG);
    }
    /* remove pages for modules which have gone (only generated ones) */
    fs.readdirSync(OUTPUT_DIR).filter(f => f.endsWith('.md') && !written.includes(f)).forEach(f => {
        let content = fs.readFileSync(path.join(OUTPUT_DIR, f), 'utf8');
        if (content.includes(MARKER)) {
            fs.unlinkSync(path.join(OUTPUT_DIR, f));
            console.log('Removed docs/api/' + f);
        }
    });
}

main().catch(error => {
    console.error(error);
    process.exit(1);
});
